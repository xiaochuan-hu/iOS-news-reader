def infer_category(text_parts: Iterable[str], fallback: str) -> str:
    haystack = f" {' '.join(text_parts).casefold()} "
    for category, keywords in KEYWORDS:
        if any(keyword in haystack for keyword in keywords):
            return category
    return fallback
